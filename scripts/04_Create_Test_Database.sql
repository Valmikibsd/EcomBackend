-- =============================================
-- Script: 04_Create_Test_Database.sql
-- Creates saksham_test database as a copy of saksham schema
-- Run on SQL Server as a DBA/sysadmin account
-- =============================================

USE [master];
GO

-- Create the test database if it doesn't exist
IF NOT EXISTS (SELECT name FROM sys.databases WHERE name = N'saksham_test')
BEGIN
    CREATE DATABASE [saksham_test];
    PRINT 'Created database: saksham_test';
END
ELSE
    PRINT 'Database saksham_test already exists — skipped.';
GO

USE [saksham_test];
GO

-- ─── Tables ──────────────────────────────────────────────

IF NOT EXISTS (SELECT * FROM sys.tables WHERE name = 'Users' AND type = 'U')
BEGIN
    CREATE TABLE [dbo].[Users] (
        [Id]           INT IDENTITY(1,1) PRIMARY KEY,
        [Username]     NVARCHAR(100) NOT NULL UNIQUE,
        [PasswordHash] NVARCHAR(500) NOT NULL,
        [Email]        NVARCHAR(200) NULL,
        [Role]         NVARCHAR(50)  NOT NULL DEFAULT 'Customer',
        [CreatedAt]    DATETIME      NOT NULL DEFAULT GETDATE()
    );
    PRINT 'Created table: Users';
END
GO

IF NOT EXISTS (SELECT * FROM sys.tables WHERE name = 'Products' AND type = 'U')
BEGIN
    CREATE TABLE [dbo].[Products] (
        [Id]          INT IDENTITY(1,1) PRIMARY KEY,
        [Name]        NVARCHAR(200) NOT NULL,
        [Description] NVARCHAR(1000) NULL,
        [Price]       DECIMAL(18,2) NOT NULL,
        [Stock]       INT NOT NULL DEFAULT 0,
        [ImageUrl]    NVARCHAR(500) NULL,
        [Category]    NVARCHAR(100) NULL,
        [Brand]       NVARCHAR(100) NULL,
        [CreatedAt]   DATETIME NOT NULL DEFAULT GETDATE(),
        [UpdatedAt]   DATETIME NULL
    );
    PRINT 'Created table: Products';
END
GO

IF NOT EXISTS (SELECT * FROM sys.tables WHERE name = 'Orders' AND type = 'U')
BEGIN
    CREATE TABLE [dbo].[Orders] (
        [Id]              INT IDENTITY(1,1) PRIMARY KEY,
        [UserId]          INT NOT NULL,
        [OrderDate]       DATETIME NOT NULL DEFAULT GETDATE(),
        [TotalAmount]     DECIMAL(18,2) NOT NULL,
        [Status]          NVARCHAR(50) NOT NULL DEFAULT 'Pending',
        [ShippingAddress] NVARCHAR(500) NULL,
        [PaymentMethod]   NVARCHAR(100) NULL,
        [PaymentStatus]   NVARCHAR(50) NULL,
        [TransactionId]   NVARCHAR(100) NULL
    );
    PRINT 'Created table: Orders';
END
GO

IF NOT EXISTS (SELECT * FROM sys.tables WHERE name = 'OrderItems' AND type = 'U')
BEGIN
    CREATE TABLE [dbo].[OrderItems] (
        [Id]          INT IDENTITY(1,1) PRIMARY KEY,
        [OrderId]     INT NOT NULL,
        [ProductId]   INT NOT NULL,
        [ProductName] NVARCHAR(200) NOT NULL,
        [UnitPrice]   DECIMAL(18,2) NOT NULL,
        [Quantity]    INT NOT NULL,
        [TotalPrice]  DECIMAL(18,2) NOT NULL,
        CONSTRAINT [FK_OrderItems_Orders_Test] FOREIGN KEY ([OrderId])
            REFERENCES [dbo].[Orders]([Id])
    );
    PRINT 'Created table: OrderItems';
END
GO

IF NOT EXISTS (SELECT * FROM sys.tables WHERE name = 'Categories' AND type = 'U')
BEGIN
    CREATE TABLE [dbo].[Categories] (
        [Id]          INT IDENTITY(1,1) PRIMARY KEY,
        [Name]        NVARCHAR(100) NOT NULL UNIQUE,
        [Description] NVARCHAR(500) NULL,
        [CreatedAt]   DATETIME NOT NULL DEFAULT GETDATE()
    );
    PRINT 'Created table: Categories';
END
GO

IF NOT EXISTS (SELECT * FROM sys.tables WHERE name = 'Brands' AND type = 'U')
BEGIN
    CREATE TABLE [dbo].[Brands] (
        [Id]          INT IDENTITY(1,1) PRIMARY KEY,
        [Name]        NVARCHAR(100) NOT NULL UNIQUE,
        [Description] NVARCHAR(500) NULL,
        [CreatedAt]   DATETIME NOT NULL DEFAULT GETDATE()
    );
    PRINT 'Created table: Brands';
END
GO

